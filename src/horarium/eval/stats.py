"""Exploratory statistics over a corpus of instances, and the tables that summarise them."""

from __future__ import annotations

import csv
import io
import statistics
from dataclasses import dataclass
from pathlib import Path

from horarium.data.ectt import read_ectt
from horarium.graph.build import build_conflict_graph
from horarium.graph.features import GLOBAL_FEATURES
from horarium.problem.checks import check_instance
from horarium.problem.instance import Instance

__all__ = ["InstanceSummary", "corpus_csv", "corpus_markdown", "summarise", "summarise_corpus"]

#: Columns shown in the compact overview table; the full table carries every measure.
HEADLINE = (
    "n_courses",
    "n_rooms",
    "n_curricula",
    "n_periods",
    "total_lectures",
    "room_period_density",
    "mean_conflict_degree",
    "conflict_density",
    "unavailability_density",
)


@dataclass(frozen=True, slots=True)
class InstanceSummary:
    """Every measure computed for one instance, keyed by measure name."""

    family: str
    stem: str
    name: str
    measures: dict[str, float]


def summarise(path: Path) -> InstanceSummary:
    """Measure one instance: the global feature block plus corpus-level diagnostics.

    Args:
        path: Path to the .ectt file.

    Returns:
        Every measure computed for this instance.
    """
    instance = read_ectt(path)
    graph = build_conflict_graph(instance)
    measures = {f.name: float(f.extract(instance, graph)) for f in GLOBAL_FEATURES}
    degrees = [d for _, d in graph.degree()]
    measures |= {
        "max_conflict_degree": float(max(degrees, default=0)),
        "n_teachers": float(len(instance.courses_of_teacher)),
        "isolated_courses": float(sum(1 for d in degrees if d == 0)),
        "room_capacity_floor": _room_capacity_floor(instance),
        "min_working_days_floor": _min_working_days_floor(instance),
        "check_warnings": float(len(check_instance(instance).warnings)),
    }
    return InstanceSummary(
        family=path.parent.name, stem=path.stem, name=instance.name, measures=measures
    )


def summarise_corpus(raw_dir: Path) -> list[InstanceSummary]:
    """Measure every .ectt file under `raw_dir`, ordered by family then file name.

    Args:
        raw_dir: The raw-data directory to scan.

    Returns:
        One summary per instance found.
    """
    return [summarise(p) for p in sorted(raw_dir.rglob("*.ectt"))]


def corpus_csv(summaries: list[InstanceSummary]) -> str:
    """Full per-instance table as CSV: one row per instance, one column per measure.

    Args:
        summaries: Per-instance summaries, e.g. from `summarise_corpus`.

    Returns:
        The CSV document as a string, including its header row.
    """
    if not summaries:
        return ""
    columns = list(summaries[0].measures)
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(["family", "file", "name", *columns])
    for row in summaries:
        writer.writerow(
            [row.family, row.stem, row.name, *(f"{row.measures[c]:g}" for c in columns)]
        )
    return buffer.getvalue()


def corpus_markdown(summaries: list[InstanceSummary]) -> str:
    """Markdown report: per-family ranges, the headline table, and the unavoidable cost floors.

    Args:
        summaries: Per-instance summaries, e.g. from `summarise_corpus`.

    Returns:
        The complete Markdown document, ending in a newline.
    """
    lines = [
        "# Instance statistics",
        "",
        "Generated by `python -m horarium.cli.prepare`. Do not edit by hand.",
        "",
        f"{len(summaries)} instances across "
        f"{len({s.family for s in summaries})} families. Every measure is also in "
        "`instance_statistics.csv`, one row per instance.",
        "",
        "## Families",
        "",
        "| family | n | courses | rooms | curricula | periods | lectures | conflict density |",
        "|---|---:|---|---|---|---|---|---|",
    ]
    for family in sorted({s.family for s in summaries}):
        members = [s for s in summaries if s.family == family]
        lines.append(
            f"| {family} | {len(members)} | "
            + " | ".join(
                _range(members, key)
                for key in (
                    "n_courses",
                    "n_rooms",
                    "n_curricula",
                    "n_periods",
                    "total_lectures",
                    "conflict_density",
                )
            )
            + " |"
        )

    lines += ["", "## Per instance", "", "| instance | " + " | ".join(HEADLINE) + " |"]
    lines.append("|---|" + "---:|" * len(HEADLINE))
    for row in summaries:
        cells = " | ".join(f"{row.measures[key]:g}" for key in HEADLINE)
        lines.append(f"| {row.family}/{row.stem} | {cells} |")

    lines += [
        "",
        "## Unavoidable cost floors",
        "",
        "Costs no schedule can avoid, because the instance itself makes them impossible to "
        "satisfy: a course with more students than its largest permitted room always pays "
        "RoomCapacity, and a course wanting more working days than it has lectures always pays "
        "MinWorkingDays. Any optimum reported below these numbers is a bug, not a result.",
        "",
        "| instance | RoomCapacity floor | MinWorkingDays floor (unweighted) |",
        "|---|---:|---:|",
    ]
    lines += [
        f"| {row.family}/{row.stem} | {row.measures['room_capacity_floor']:g} "
        f"| {row.measures['min_working_days_floor']:g} |"
        for row in summaries
        if row.measures["room_capacity_floor"] or row.measures["min_working_days_floor"]
    ]
    return "\n".join([*lines, ""])


def _range(members: list[InstanceSummary], key: str) -> str:
    """Min-max range of a measure across a family, or the single value if they agree.

    Args:
        members: The family's instance summaries.
        key: Which measure to range over.

    Returns:
        A formatted range, e.g. `"30-131 (med 82)"`, or a single value when they all agree.
    """
    values = [m.measures[key] for m in members]
    low, high = min(values), max(values)
    if low == high:
        return f"{low:g}"
    return f"{low:g}-{high:g} (med {statistics.median(values):g})"


def _room_capacity_floor(instance: Instance) -> float:
    """Least RoomCapacity cost achievable: every lecture in the largest room it is allowed.

    Args:
        instance: The instance to measure.

    Returns:
        The minimum RoomCapacity cost any solution of this instance must pay.
    """
    total = 0
    for index, course in enumerate(instance.courses):
        best = max((instance.rooms[r].capacity for r in instance.permitted_rooms[index]), default=0)
        total += course.n_lectures * max(0, course.n_students - best)
    return float(total)


def _min_working_days_floor(instance: Instance) -> float:
    """Least MinWorkingDays cost achievable: a course cannot span more days than it has lectures.

    Args:
        instance: The instance to measure.

    Returns:
        The minimum (unweighted) MinWorkingDays cost any solution of this instance must pay.
    """
    return float(
        sum(
            max(0, course.min_working_days - min(course.n_lectures, instance.days))
            for course in instance.courses
        )
    )
